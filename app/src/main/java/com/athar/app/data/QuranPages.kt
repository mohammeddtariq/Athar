    /**
     * Returns the 1-indexed Madani Mushaf page number (1..604) for a given [surah] and [ayah].
     */
    fun getPageForVerse(surah: Int, ayah: Int): Int {
        val target = (surah shl 16) or ayah
        val idx = QURAN_PAGE_STARTS.binarySearch(target)
        return if (idx >= 0) idx + 1 else -idx - 1
    }

    /**
     * Returns the 1-indexed page range (1..604) for a given [surahNumber] and [totalAyahs].
     */
    fun getPagesForSurah(surahNumber: Int, totalAyahs: Int): List<Int> {
        val startPage = getPageForVerse(surahNumber, 1)
        val endPage = getPageForVerse(surahNumber, totalAyahs)
        return (startPage..endPage).toList()
    }

    /**
     * Groups a surah's verses by their canonical Mushaf pages so that verses flow
     * continuously per page and can be separated by authentic page ending dividers.
     */
    fun getSurahPageChunks(surah: Int, verses: List<QuranVerse>): List<QuranPageChunk> {
        if (verses.isEmpty()) return emptyList()
        val chunks = mutableListOf<QuranPageChunk>()
        var currentPage = getPageForVerse(surah, verses.first().number)
        val currentList = mutableListOf<QuranVerse>()

        for (i in verses.indices) {
            val v = verses[i]
            val p = getPageForVerse(surah, v.number)
            if (p != currentPage && currentList.isNotEmpty()) {
                chunks.add(QuranPageChunk(currentPage, currentList.toList(), false))
                currentList.clear()
                currentPage = p
            }
            currentList.add(v)
        }
        if (currentList.isNotEmpty()) {
            chunks.add(QuranPageChunk(currentPage, currentList.toList(), true))
        }
        return chunks
    }
